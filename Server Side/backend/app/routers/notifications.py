"""WattWise — Notifications Router."""

from datetime import datetime, timedelta
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Request, Query
from sqlalchemy import select, func, update as sql_update, case
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models import Notification, UserInteractionLog, Device, UserDecision
from app.schemas import NotificationResponse, NotificationStatsResponse, DecisionBrief

router = APIRouter(prefix="/api/notifications", tags=["Notifications"])

# ── Alerts vs Notifications ───────────────────────────────────
# "Notifications" = messages an admin sent by hand; "Alerts" = generated by the rule
# engine from the home's data. Both are decision-tracked. The split uses the
# `source` column; ADMIN_BROADCAST is kept as a fallback for rows older than it.
ADMIN_NOTIFICATION_TYPES = ("ADMIN_BROADCAST",)


_COLUMNS = tuple(Notification.__table__.columns)


def _is_admin_message():
    return (Notification.source == "ADMIN") | Notification.notification_type.in_(ADMIN_NOTIFICATION_TYPES)


def _apply_category(q, category: Optional[str]):
    if category == "alerts":
        return q.where(~_is_admin_message())
    if category == "notifications":
        return q.where(_is_admin_message())
    return q


def _undecided():
    """No decision recorded yet for this alert."""
    return ~Notification.id.in_(
        select(UserDecision.notification_id).where(UserDecision.notification_id.isnot(None))
    )


def _get_user_id(request: Request) -> int:
    user_id = getattr(request.state, "user_id", None)
    if not user_id:
        raise HTTPException(status_code=401, detail="Not authenticated")
    return user_id


async def _to_responses(db: AsyncSession, user_id: int, notifs: list[Notification]) -> list[NotificationResponse]:
    """Attach each alert's decision and device, so the client never has to guess state."""
    if not notifs:
        return []
    ids = [n.id for n in notifs]
    decisions = {
        d.notification_id: d
        for d in (await db.execute(
            select(UserDecision).where(UserDecision.user_id == user_id, UserDecision.notification_id.in_(ids))
        )).scalars().all()
    }
    device_ids = {n.device_id for n in notifs if n.device_id}
    devices = {}
    if device_ids:
        devices = {
            d.id: d for d in (await db.execute(select(Device).where(Device.id.in_(device_ids)))).scalars().all()
        }
    now = datetime.utcnow()
    out = []
    for n in notifs:
        # Build from columns only: validating the ORM object would touch the lazy
        # `decision` relationship, which cannot load inside an async session.
        resp = NotificationResponse.model_validate({c.name: getattr(n, c.name) for c in _COLUMNS})
        resp.is_expired = bool(n.expires_at and n.expires_at < now)
        dev = devices.get(n.device_id)
        if dev:
            resp.device_name = dev.name
            resp.appliance_key = dev.appliance_key
        d = decisions.get(n.id)
        if d:
            resp.decision = DecisionBrief.model_validate(d)
        out.append(resp)
    return out


async def _own_notification(db: AsyncSession, notification_id: int, user_id: int) -> Notification:
    notif = (await db.execute(
        select(Notification).where(Notification.id == notification_id, Notification.user_id == user_id)
    )).scalar_one_or_none()
    if not notif:
        raise HTTPException(status_code=404, detail="Notification not found")
    return notif


@router.get("/", response_model=list[NotificationResponse])
async def list_notifications(
    request: Request,
    db: AsyncSession = Depends(get_db),
    page: int = Query(default=1, ge=1),
    limit: int = Query(default=20, ge=1, le=100),
    filter: Optional[str] = Query(default="all"),
    category: Optional[str] = Query(default="all", description="all | alerts | notifications"),
    since_id: Optional[int] = Query(default=None, description="Only alerts with id greater than this (polling)"),
):
    user_id = _get_user_id(request)
    q = select(Notification).where(Notification.user_id == user_id)
    if filter == "unread":
        q = q.where(~Notification.is_read)
    elif filter == "critical":
        q = q.where(Notification.severity == "CRITICAL")
    elif filter == "dismissed":
        q = q.where(Notification.dismissed)
    elif filter == "action_required":
        # Still waiting for the user: actionable, not dismissed, not expired, no decision yet.
        q = q.where(
            Notification.requires_user_action, ~Notification.dismissed, _undecided(),
            (Notification.expires_at.is_(None)) | (Notification.expires_at >= datetime.utcnow()),
        )
    if since_id is not None:
        q = q.where(Notification.id > since_id)
    q = _apply_category(q, category)
    q = q.order_by(Notification.created_at.desc()).offset((page - 1) * limit).limit(limit)
    notifs = list((await db.execute(q)).scalars().all())
    return await _to_responses(db, user_id, notifs)


@router.get("/history", response_model=list[NotificationResponse])
async def list_notifications_history(
    request: Request,
    db: AsyncSession = Depends(get_db),
    limit: int = Query(default=30, ge=1, le=100),
    unread_only: bool = Query(default=False),
):
    """Compatibility alias for Android builds that poll /history (they got 404/405 before)."""
    return await list_notifications(
        request, db, page=1, limit=limit, filter="unread" if unread_only else "all", category="all", since_id=None,
    )


@router.get("/stats", response_model=NotificationStatsResponse)
async def get_stats(
    request: Request, db: AsyncSession = Depends(get_db),
    category: Optional[str] = Query(default="all", description="all | alerts | notifications"),
):
    user_id = _get_user_id(request)
    today = datetime.utcnow().replace(hour=0, minute=0, second=0, microsecond=0)

    async def count(*extra_where):
        q = select(func.count(Notification.id)).where(Notification.user_id == user_id)
        for clause in extra_where:
            q = q.where(clause)
        q = _apply_category(q, category)
        r = await db.execute(q)
        return r.scalar() or 0

    total = await count()
    unread = await count(~Notification.is_read)
    critical = await count(Notification.severity == "CRITICAL")
    today_count = await count(Notification.created_at >= today)
    requires_action = await count(
        Notification.requires_user_action, ~Notification.dismissed, _undecided(),
        (Notification.expires_at.is_(None)) | (Notification.expires_at >= datetime.utcnow()),
    )

    return NotificationStatsResponse(
        total=total, unread=unread, critical=critical,
        today=today_count, requires_action=requires_action
    )


@router.get("/stats/breakdown")
async def get_stats_breakdown(request: Request, db: AsyncSession = Depends(get_db)):
    """
    Detailed breakdown of this user's notifications:
      - by notification_type
      - by severity
      - by appliance (resolved via device_id)
      - by time bucket: last 24h, last 7d, last 30d, all-time
    Ported from old getNotificationStats endpoint with richer dimensions.
    """
    user_id = _get_user_id(request)
    now = datetime.utcnow()
    last_24h = now - timedelta(hours=24)
    last_7d = now - timedelta(days=7)
    last_30d = now - timedelta(days=30)

    # By notification_type
    by_type_q = await db.execute(
        select(Notification.notification_type, func.count(Notification.id))
        .where(Notification.user_id == user_id)
        .group_by(Notification.notification_type)
        .order_by(func.count(Notification.id).desc())
    )
    by_type = [{"type": t or "unknown", "count": int(c)} for t, c in by_type_q.all()]

    # By severity
    by_severity_q = await db.execute(
        select(Notification.severity, func.count(Notification.id))
        .where(Notification.user_id == user_id)
        .group_by(Notification.severity)
    )
    by_severity = [{"severity": s or "INFO", "count": int(c)} for s, c in by_severity_q.all()]

    # By appliance (joined via Device)
    by_appliance_q = await db.execute(
        select(Device.appliance_key, func.count(Notification.id))
        .join(Notification, Notification.device_id == Device.id)
        .where(Notification.user_id == user_id, Device.appliance_key.is_not(None))
        .group_by(Device.appliance_key)
        .order_by(func.count(Notification.id).desc())
    )
    by_appliance = [{"appliance": a, "count": int(c)} for a, c in by_appliance_q.all()]

    # By time bucket
    async def count_since(ts):
        q = select(func.count(Notification.id)).where(
            Notification.user_id == user_id,
            Notification.created_at >= ts,
        )
        return int((await db.execute(q)).scalar() or 0)

    async def count_total():
        q = select(func.count(Notification.id)).where(Notification.user_id == user_id)
        return int((await db.execute(q)).scalar() or 0)

    by_period = {
        "last_24h": await count_since(last_24h),
        "last_7d": await count_since(last_7d),
        "last_30d": await count_since(last_30d),
        "all_time": await count_total(),
    }

    # Read/unread/dismissed split (handy for the bell-badge donut)
    state_q = await db.execute(
        select(
            func.sum(case((Notification.is_read, 1), else_=0)).label("read"),
            func.sum(case((Notification.is_read, 0), else_=1)).label("unread"),
            func.sum(case((Notification.dismissed, 1), else_=0)).label("dismissed"),
            func.sum(case((Notification.opened_at.isnot(None), 1), else_=0)).label("opened"),
        ).where(Notification.user_id == user_id)
    )
    state_row = state_q.one()
    state = {
        "read": int(state_row.read or 0),
        "unread": int(state_row.unread or 0),
        "dismissed": int(state_row.dismissed or 0),
        "opened": int(state_row.opened or 0),
    }

    return {
        "by_type": by_type,
        "by_severity": by_severity,
        "by_appliance": by_appliance,
        "by_period": by_period,
        "state": state,
        "generated_at": now.isoformat(),
    }


@router.post("/{notification_id}/open", response_model=NotificationResponse)
async def open_notification(notification_id: int, request: Request, db: AsyncSession = Depends(get_db)):
    """
    The user explicitly opened this alert (tapped the card, or tapped the phone
    notification). Recorded once: `opened_at` is the research timestamp for "saw and
    engaged with the alert", distinct from `is_read` (merely listed on screen).
    """
    user_id = _get_user_id(request)
    notif = await _own_notification(db, notification_id, user_id)
    # Whole seconds: the column is DATETIME(0), so a later read returns exactly this value.
    now = datetime.utcnow().replace(microsecond=0)
    if notif.opened_at is None:
        notif.opened_at = now
        db.add(UserInteractionLog(
            user_id=user_id, interaction_type="VIEW_NOTIFICATION", notification_id=notification_id,
            device_id=notif.device_id, screen_name="alert_detail",
        ))
    if not notif.is_read:
        notif.is_read = True
        notif.read_at = now
    await db.commit()
    return (await _to_responses(db, user_id, [notif]))[0]


@router.patch("/{notification_id}/read", response_model=NotificationResponse)
async def mark_read(notification_id: int, request: Request, db: AsyncSession = Depends(get_db)):
    """Mark as seen in a list. The first read time is kept; repeat calls change nothing."""
    user_id = _get_user_id(request)
    notif = await _own_notification(db, notification_id, user_id)
    if not notif.is_read:
        notif.is_read = True
        notif.read_at = datetime.utcnow()
        await db.commit()
    return (await _to_responses(db, user_id, [notif]))[0]


@router.post("/{notification_id}/read", response_model=NotificationResponse)
async def mark_read_post(
    notification_id: int, request: Request, db: AsyncSession = Depends(get_db)
):
    """POST alias for PATCH /{id}/read used by the frontend."""
    return await mark_read(notification_id, request, db)


@router.patch("/read-all", status_code=204)
async def mark_all_read(request: Request, db: AsyncSession = Depends(get_db)):
    user_id = _get_user_id(request)
    now = datetime.utcnow()
    await db.execute(
        sql_update(Notification)
        .where(Notification.user_id == user_id, ~Notification.is_read)
        .values(is_read=True, read_at=now)
    )
    await db.commit()


@router.patch("/{notification_id}/dismiss", response_model=NotificationResponse)
async def dismiss_notification(notification_id: int, request: Request, db: AsyncSession = Depends(get_db)):
    user_id = _get_user_id(request)
    notif = await _own_notification(db, notification_id, user_id)
    now = datetime.utcnow()
    notif.dismissed = True
    notif.dismissed_at = now
    if not notif.is_read:
        notif.is_read = True
        notif.read_at = now
    await db.commit()
    return (await _to_responses(db, user_id, [notif]))[0]


@router.delete("/{notification_id}", status_code=204)
async def delete_notification(notification_id: int, request: Request, db: AsyncSession = Depends(get_db)):
    user_id = _get_user_id(request)
    notif = await _own_notification(db, notification_id, user_id)
    await db.delete(notif)
    await db.commit()
