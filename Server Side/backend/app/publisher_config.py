"""
Generates the RPi publisher's YAML for a provisioned home.

The admin gets this file from the portal and pastes it into the WattWise Publisher
add-on on the participant's Raspberry Pi (/config/wattwise_publisher.yaml). Everything
the server knows is filled in; the only things left for the Pi are its own InfluxDB
password and, per device, the InfluxDB tag (power_entity_id) if it differs from the
suggested name.
"""
import re
from typing import Optional


def _q(value) -> str:
    """Double-quoted YAML scalar."""
    return '"' + str(value if value is not None else "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def slug(name: str) -> str:
    """A device's short id in the MQTT topic: lowercase letters, digits and underscores."""
    s = re.sub(r"[^a-z0-9]+", "_", (name or "").strip().lower()).strip("_")
    return s or "device"


def suggested_power_entity(appliance_key: str) -> str:
    """Home Assistant's usual InfluxDB tag for a Tapo plug's power sensor."""
    return f"{slug(appliance_key)}_current_consumption"


def build_publisher_yaml(
    *,
    mqtt_username: str,
    mqtt_password: Optional[str],
    home_name: str,
    devices: list[dict],
    mqtt_host: str,
    mqtt_port: int = 1883,
    interval_seconds: int = 30,
) -> str:
    """
    devices: [{name, appliance_key, entity_id, power_entity_id?}]
    mqtt_password None → a placeholder is written (used when re-downloading the file;
    the password is only ever shown once, at provisioning or rotation).
    """
    lines = [
        "# WattWise RPi publisher — generated by the admin portal",
        f"# Home: {home_name}  ·  broker account: {mqtt_username}",
        "#",
        "# Paste into the WattWise Publisher add-on config (/config/wattwise_publisher.yaml)",
        "# on this home's Raspberry Pi, set the InfluxDB password, then restart the add-on.",
        "# Do not change home.id or any entity_id: the server matches readings on them.",
        "",
        "home:",
        f"  id: {_q(mqtt_username)}          # MQTT topic: wattwise/homes/{mqtt_username}/devices/<id>/data",
        f"  name: {_q(home_name)}",
        "  devices:",
    ]
    used_ids: set[str] = set()
    for d in devices:
        device_id = slug(d.get("appliance_key") or d.get("name") or "device")
        base, n = device_id, 2
        while device_id in used_ids:
            device_id = f"{base}_{n}"
            n += 1
        used_ids.add(device_id)
        power_entity = d.get("power_entity_id") or suggested_power_entity(d.get("appliance_key") or d.get("name") or "")
        lines += [
            f"    - id: {_q(device_id)}",
            f"      name: {_q(d.get('name'))}",
            f"      appliance_key: {_q(d.get('appliance_key'))}",
            f"      entity_id: {_q(d.get('entity_id'))}            # server-side id — keep exactly",
            f"      power_entity_id: {_q(power_entity)}   # this Pi's InfluxDB tag — confirm with:",
            "      #   SHOW TAG VALUES FROM \"W\" WITH KEY = \"entity_id\"",
        ]
    if not devices:
        lines.append("    []")
    lines += [
        "",
        "influxdb:                      # Home Assistant's InfluxDB add-on on this Pi",
        '  host: "localhost"',
        "  port: 8086",
        '  database: "homeassistant"',
        '  username: "homeassistant"',
        '  password: "REPLACE_WITH_INFLUXDB_PASSWORD"   # this Pi\'s /config/secrets.yaml → influxdb_password',
        "  ssl: false",
        "",
        "mqtt:",
        f"  host: {_q(mqtt_host)}",
        f"  port: {int(mqtt_port)}",
        '  transport: "tcp"',
        '  ws_path: ""',
        f"  username: {_q(mqtt_username)}",
        f"  password: {_q(mqtt_password) if mqtt_password else _q('PASTE_THE_MQTT_PASSWORD_SHOWN_AT_PROVISIONING')}",
        "  tls: false",
        "",
        f"publish_interval_seconds: {int(interval_seconds)}",
        "stale_after_seconds: 900       # stop re-sending a non-idle value unchanged for this long (plug offline)",
        'log_level: "INFO"',
        "",
    ]
    return "\n".join(lines)
