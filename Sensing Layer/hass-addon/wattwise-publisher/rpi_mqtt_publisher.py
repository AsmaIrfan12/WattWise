#!/usr/bin/env python3
"""
WattWise RPi MQTT Publisher
============================
Runs on each Raspberry Pi (Home Assistant host).
Reads energy telemetry from local InfluxDB and publishes to
the WattWise cloud MQTT broker every 30 seconds.

Replaces Tailscale tunnelling for community-scale deployments.

Author : Mr. Suhas Devmane, Cardiff University, UK
Version: 1.0.0
"""

import json
import logging
import signal
import sys
import time
from datetime import datetime, timezone

import paho.mqtt.client as mqtt
import yaml
from influxdb import InfluxDBClient

# ── Logging ───────────────────────────────────────────────────────────────────
_handlers = [logging.StreamHandler(sys.stdout)]
try:
    # Size-capped file log (the old plain FileHandler grew without limit). Optional:
    # in the Home Assistant add-on the container log is what people read.
    from logging.handlers import RotatingFileHandler
    _handlers.append(RotatingFileHandler("/var/log/wattwise-publisher.log", maxBytes=2_000_000, backupCount=3))
except OSError:
    pass
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    handlers=_handlers,
)
logger = logging.getLogger("wattwise.publisher")


# ── Config Loader ──────────────────────────────────────────────────────────────
def load_config(path: str = "/etc/wattwise/publisher.yaml") -> dict:
    """Load and validate YAML config file. Exits loudly on missing credentials."""
    try:
        with open(path, "r") as f:
            cfg = yaml.safe_load(f)
    except FileNotFoundError:
        logger.error(f"Config file not found: {path}")
        logger.info("Copy rpi_publisher_config.yaml to /etc/wattwise/publisher.yaml")
        sys.exit(1)

    # Credential guard — refuse to start with blank or placeholder values
    mqtt_cfg = cfg.get("mqtt", {})
    username = (mqtt_cfg.get("username") or "").strip()
    password = (mqtt_cfg.get("password") or "").strip()

    def _placeholder(value) -> bool:
        v = str(value or "").strip()
        return not v or v.startswith("REPLACE_") or v.startswith("PASTE_")

    errors = []
    if _placeholder(username):
        errors.append("mqtt.username is blank or a placeholder — paste the config generated by the admin portal")
    if _placeholder(password):
        errors.append("mqtt.password is blank or still a placeholder — use the password shown when the home was created")
    if _placeholder(mqtt_cfg.get("host")):
        errors.append("mqtt.host is blank or a placeholder")
    if _placeholder((cfg.get("home") or {}).get("id")):
        errors.append("home.id is blank or a placeholder — it must be this home's MQTT username (e.g. home_016)")

    if errors:
        logger.error("=" * 60)
        logger.error("CONFIGURATION ERROR — publisher cannot start:")
        for e in errors:
            logger.error(f"  • {e}")
        logger.error(f"Edit {path} and fill in your credentials.")
        logger.error("=" * 60)
        sys.exit(1)

    logger.info(f"✅ Config loaded from {path} (home_id={cfg.get('home', {}).get('id')}, mqtt_user={username})")
    return cfg


# ── InfluxDB Reader ────────────────────────────────────────────────────────────
PUBLISHER_VERSION = "1.1.0"


class InfluxReader:
    """Reads latest sensor readings from local InfluxDB v1.x (Home Assistant)."""

    def __init__(self, cfg: dict):
        self.client = InfluxDBClient(
            host=cfg.get("host", "localhost"),
            port=cfg.get("port", 8086),
            username=cfg.get("username", ""),
            password=cfg.get("password", ""),
            database=cfg.get("database", "homeassistant"),
            ssl=cfg.get("ssl", False),
            timeout=10,
        )
        logger.info(
            f"📊 InfluxDB reader initialised: "
            f"{cfg.get('host')}:{cfg.get('port')}/{cfg.get('database')}"
        )
        self._last_err_log = 0.0   # monotonic ts of last throttled query-error warning

    def get_latest(self, entity_id: str, measurement: str = "state") -> dict | None:
        """Get most recent value for an entity_id. Uses parameterized WHERE clause."""
        # Sanitize entity_id to prevent injection (only alphanumeric, _, ., -)
        import re
        safe_entity = re.sub(r"[^a-zA-Z0-9_\.\-]", "", entity_id)
        if safe_entity != entity_id:
            logger.warning(f"entity_id sanitized: '{entity_id}' → '{safe_entity}'")
            entity_id = safe_entity

        # InfluxDB 1.x doesn't support proper parameterized queries for tag values;
        # We sanitize the input above and use quoted string literals.
        query = (
            f'SELECT value, state FROM "{measurement}" '
            f"WHERE entity_id = '{entity_id}' "
            f"ORDER BY time DESC LIMIT 1"
        )
        try:
            result = list(self.client.query(query).get_points())
            if result:
                return result[0]
        except Exception as e:
            logger.warning(f"InfluxDB query error for {entity_id}: {e}")
        return None

    def get_energy_kwh(self, entity_id: str) -> dict | None:
        """Fetch latest energy kWh reading. Sanitizes entity_id before querying."""
        import re
        import math
        import time as _time
        safe_entity = re.sub(r"[^a-zA-Z0-9_\.\-]", "", entity_id)
        entity_id = safe_entity

        last_error = None
        for measurement in ["kWh", "W", "state"]:
            try:
                query = (
                    f'SELECT value FROM "{measurement}" '
                    f"WHERE entity_id = '{entity_id}' "
                    f"ORDER BY time DESC LIMIT 1"
                )
                result = list(self.client.query(query).get_points())
                if result:
                    raw = float(result[0].get("value", 0) or 0)
                    # Validate: reject NaN, Inf, negative, impossibly large values
                    if math.isnan(raw) or math.isinf(raw) or raw < 0 or raw > 50000:
                        logger.warning(f"Invalid sensor value for {entity_id}: {raw}")
                        return None
                    return {"value": raw, "measurement": measurement, "time": result[0].get("time")}
            except Exception as e:
                last_error = e
                continue
        # Surface query errors instead of silently returning 0-published. Throttled to
        # once per 5 min so a persistent problem (e.g. wrong influxdb.username/password,
        # or the add-on requiring auth) is visible in the logs without spamming.
        if last_error is not None:
            now = _time.monotonic()
            if now - self._last_err_log > 300:
                self._last_err_log = now
                logger.warning(
                    f"InfluxDB query failed for '{entity_id}': {last_error} — check "
                    f"influxdb.username/password in the config and that the InfluxDB "
                    f"add-on is reachable (queries need auth even when /ping succeeds)."
                )
        return None

    def ping(self) -> bool:
        try:
            self.client.ping()
            return True
        except Exception:
            return False


## ── MQTT Publisher ─────────────────────────────────────────────────────────────
class MQTTPublisher:
    """Authenticated MQTT client for the WattWise cloud broker."""

    def __init__(self, cfg: dict, home_id: str):
        self.home_id = home_id
        self.cfg = cfg
        self.connected = False

        transport = cfg.get("transport", "tcp")   # "tcp" or "websockets"
        self.client = mqtt.Client(
            client_id=f"wattwise-rpi-{home_id}",
            protocol=mqtt.MQTTv5,
            transport=transport,
        )

        # WebSocket path (only used when transport="websockets")
        if transport == "websockets":
            self.client.ws_set_options(path=cfg.get("ws_path", "/mqtt"))

        # Authentication
        if cfg.get("username") and cfg.get("password"):
            self.client.username_pw_set(cfg["username"], cfg["password"])

        # TLS/SSL — required for WSS (Cloudflare) or explicit tls:true
        if cfg.get("tls", False) or transport == "websockets":
            self.client.tls_set()  # uses system CA bundle (trusts Cloudflare cert)

        # Last will: if this Pi drops off without saying goodbye (power cut, network loss),
        # the broker itself tells the server the home is offline.
        self.status_topic = f"wattwise/homes/{home_id}/status"
        self.client.will_set(
            self.status_topic,
            json.dumps({"home_id": home_id, "status": "offline", "reason": "connection_lost"}),
            qos=1, retain=True,
        )

        # Callbacks
        self.client.on_connect = self._on_connect
        self.client.on_disconnect = self._on_disconnect
        self.client.on_publish = self._on_publish

    def _on_connect(self, client, userdata, flags, rc, props=None):
        if rc == 0:
            self.connected = True
            logger.info(f"✅ MQTT connected to {self.cfg['host']}:{self.cfg.get('port', 1883)}")
            # Replace any retained "offline" (from a last will) straight away.
            client.publish(
                self.status_topic,
                json.dumps({"home_id": self.home_id, "status": "online",
                            "timestamp": datetime.now(timezone.utc).isoformat(),
                            "publisher_version": PUBLISHER_VERSION}),
                qos=1, retain=True,
            )
        else:
            logger.error(f"❌ MQTT connect failed (rc={rc}): {mqtt.connack_string(rc)}")

    def _on_disconnect(self, client, userdata, rc, props=None):
        self.connected = False
        if rc != 0:
            logger.warning(f"MQTT unexpected disconnect (rc={rc}), will reconnect...")

    def _on_publish(self, client, userdata, mid):
        logger.debug(f"📤 MQTT message published (mid={mid})")

    def connect(self):
        """Connect to MQTT broker with exponential backoff retry."""
        import time as _time
        max_retries = 10
        base_delay = 2.0
        for attempt in range(max_retries):
            try:
                self.client.connect(
                    self.cfg["host"],
                    self.cfg.get("port", 1883),
                    keepalive=60,
                )
                self.client.loop_start()
                _time.sleep(2)  # Allow connection to establish
                if self.connected:
                    return
                raise ConnectionError("MQTT connected but not acknowledged")
            except Exception as e:
                delay = min(base_delay * (2 ** attempt), 120)
                logger.warning(
                    f"MQTT connection attempt {attempt + 1}/{max_retries} failed: {e}. "
                    f"Retrying in {delay:.0f}s..."
                )
                _time.sleep(delay)
        raise RuntimeError(f"Failed to connect to MQTT broker after {max_retries} attempts")

    def publish_device(self, device_id: str, payload: dict) -> bool:
        """Publish device telemetry to wattwise/homes/{home_id}/devices/{device_id}/data"""
        topic = f"wattwise/homes/{self.home_id}/devices/{device_id}/data"
        payload_str = json.dumps(payload)

        result = self.client.publish(topic, payload_str, qos=1, retain=False)
        if result.rc == mqtt.MQTT_ERR_SUCCESS:
            logger.debug(f"📤 Published {device_id}: {payload_str[:80]}")
            return True
        else:
            logger.error(f"Publish failed for {device_id}: rc={result.rc}")
            return False

    def publish_home_status(self, status: dict):
        """Publish RPi heartbeat to wattwise/homes/{home_id}/status"""
        self.client.publish(self.status_topic, json.dumps(status), qos=1, retain=True)

    def disconnect(self):
        self.client.loop_stop()
        self.client.disconnect()


# ── Stale-value detection (pure helpers, unit-tested on the server side) ─────────
def reading_age(point_time, now):
    """(ISO time of the InfluxDB point, seconds since then) — (None, None) if unknown."""
    if not point_time:
        return None, None
    try:
        parsed = datetime.fromisoformat(str(point_time).replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.isoformat(), max((now - parsed).total_seconds(), 0.0)
    except (ValueError, TypeError):
        return None, None


def is_stale(power_w, age_seconds, stale_after_seconds, idle_watts):
    """A value above idle that has not changed for stale_after_seconds (0 disables the check)."""
    if not stale_after_seconds or age_seconds is None:
        return False
    return power_w > idle_watts and age_seconds > stale_after_seconds


# ── Main Publisher Loop ────────────────────────────────────────────────────────
class WattWisePublisher:
    """Main orchestrator: reads InfluxDB → publishes to MQTT cloud."""

    def __init__(self, config_path: str = "/etc/wattwise/publisher.yaml"):
        self.cfg = load_config(config_path)
        self.home_id = self.cfg["home"]["id"]
        self.devices = self.cfg["home"]["devices"]
        self.interval = self.cfg.get("publish_interval_seconds", 30)
        # Home Assistant only writes a point when a value changes, so the publisher
        # re-sends the latest one each cycle. That is right for an idle plug (0 W for
        # hours) but wrong for a plug that went offline mid-use: its last "2000 W"
        # would be repeated forever as phantom consumption. A non-idle value that has
        # not changed for this long is treated as stale and not published.
        self.stale_after = int(self.cfg.get("stale_after_seconds", 900))
        self.idle_watts = float(self.cfg.get("idle_watts", 5.0))
        self.stale_devices: set = set()
        self.running = True

        self.influx = InfluxReader(self.cfg["influxdb"])
        self.mqtt = MQTTPublisher(self.cfg["mqtt"], self.home_id)

        # Graceful shutdown
        signal.signal(signal.SIGTERM, self._handle_signal)
        signal.signal(signal.SIGINT, self._handle_signal)

    def _handle_signal(self, signum, frame):
        logger.info(f"Received signal {signum}, shutting down...")
        self.running = False

    def _build_payload(self, device: dict) -> dict | None:
        """Read all entity IDs for a device and build telemetry payload."""
        entity_id = device["entity_id"]
        power_entity = device.get("power_entity_id", entity_id)
        switch_entity = device.get("switch_entity_id")

        # Power reading (Watts)
        power_data = self.influx.get_energy_kwh(power_entity)
        power_w = power_data["value"] if power_data else None

        # Current reading (Amps) — optional
        current_entity = device.get("current_entity_id")
        current_a = None
        if current_entity:
            c = self.influx.get_latest(current_entity)
            if c:
                try:
                    current_a = float(c.get("value", 0))
                except (TypeError, ValueError):
                    pass

        # Switch state — optional
        switch_state = None
        if switch_entity:
            sw = self.influx.get_latest(switch_entity)
            if sw:
                switch_state = sw.get("state", "unknown")

        if power_w is None:
            logger.debug(f"No power data for {entity_id}, skipping")
            return None

        # How old is the value we are about to (re)send?
        source_time, age_seconds = reading_age(power_data.get("time"), datetime.now(timezone.utc))
        if is_stale(power_w, age_seconds, self.stale_after, self.idle_watts):
            if device["id"] not in self.stale_devices:
                logger.warning(
                    f"⏸  {device['id']}: {power_w} W unchanged for {int(age_seconds)}s — plug looks offline, "
                    f"not publishing until Home Assistant records a new value"
                )
            self.stale_devices.add(device["id"])
            return None
        self.stale_devices.discard(device["id"])

        # Estimate: energy_kwh = power_W / 1000 * interval_h
        interval_hours = self.interval / 3600
        energy_kwh = (power_w / 1000.0) * interval_hours

        # Estimate voltage (UK standard 230V)
        voltage_v = 230.0
        current_a = current_a or (power_w / voltage_v if power_w > 0 else 0.0)

        return {
            "home_id": self.home_id,
            "device_id": device["id"],
            "entity_id": entity_id,
            "device_name": device.get("name", entity_id),
            "appliance_key": device.get("appliance_key", device["id"]),
            "power_watts": round(power_w, 2),
            "current_amps": round(current_a, 3),
            "voltage_volts": voltage_v,
            "energy_kwh": round(energy_kwh, 6),
            "switch_state": switch_state,
            # When this sample was taken (now). The value itself may be older — see below.
            "timestamp": datetime.now(timezone.utc).isoformat(),
            # When Home Assistant last recorded this value, and how long ago that was.
            "source_timestamp": source_time,
            "age_seconds": None if age_seconds is None else int(age_seconds),
        }

    def run(self):
        """Main publishing loop."""
        logger.info(f"🚀 WattWise Publisher starting for home_id={self.home_id}")
        logger.info(f"   Devices: {[d['id'] for d in self.devices]}")
        logger.info(f"   Publish interval: {self.interval}s")

        # Connect MQTT
        self.mqtt.connect()

        if not self.flux_check():
            logger.error("InfluxDB not reachable — check local InfluxDB service")

        loop_count = 0
        while self.running:
            loop_count += 1
            published = 0
            errors = 0

            for device in self.devices:
                try:
                    payload = self._build_payload(device)
                    if payload:
                        success = self.mqtt.publish_device(device["id"], payload)
                        if success:
                            published += 1
                        else:
                            errors += 1
                except Exception as e:
                    logger.error(f"Error processing device {device.get('id')}: {e}")
                    errors += 1

            # Heartbeat every 10 loops
            if loop_count % 10 == 0:
                self.mqtt.publish_home_status({
                    "home_id": self.home_id,
                    "status": "stale" if (self.stale_devices and not published) else "online",
                    "devices_active": published,
                    "devices_stale": sorted(self.stale_devices),
                    "timestamp": datetime.now(timezone.utc).isoformat(),
                    "publisher_version": PUBLISHER_VERSION,
                })
                logger.info(
                    f"💚 Heartbeat #{loop_count}: {published} published, {errors} errors"
                )
            else:
                logger.info(f"🔄 Loop #{loop_count}: {published} published, {errors} errors")

            # Wait for next interval
            for _ in range(self.interval):
                if not self.running:
                    break
                time.sleep(1)

        # Cleanup
        self.mqtt.publish_home_status({
            "home_id": self.home_id,
            "status": "offline",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })
        self.mqtt.disconnect()
        logger.info("WattWise Publisher stopped cleanly.")

    def flux_check(self) -> bool:
        ok = self.influx.ping()
        logger.info(f"InfluxDB ping: {'✅ OK' if ok else '❌ FAIL'}")
        return ok


